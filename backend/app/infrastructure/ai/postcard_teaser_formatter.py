"""Форматирование короткой открытки-поздравления для канала «Открытки»."""


def is_postcard_article_channel(channel_name: str) -> bool:
    """Определяет, нужен ли формат короткой открытки.

    Args:
        channel_name: название канала.

    Returns:
        bool: True для канала «Открытки».
    """
    return "открытк" in channel_name.lower()


def postcard_writing_instructions(teaser_max_length: int) -> str:
    """Возвращает инструкции для ArticleWriter (короткая открытка).

    Полностью переопределяет структуру и объём body_html из базового
    шаблона — это открытка на 1-2 предложения, а не статья с разделами.

    Args:
        teaser_max_length: лимит анонса (актуальной длины поста).

    Returns:
        str: блок инструкций на русском.
    """
    return f"""ВАЖНО: игнорируй указания по структуре и объёму body_html выше —
здесь другое правило. Это короткая открытка-поздравление, а не статья.

Ответь JSON с ключами: title, teaser, body_html, image_prompt.

- teaser — САМ ТЕКСТ ОТКРЫТКИ: 1-2 тёплых предложения по поводу темы,
  от души, без канцелярита. МНОГО уместных эмодзи (не перебарщивай до
  нечитаемости, но 3-6 штук по тексту — норма). Никаких хэштегов.
- body_html — ОДНА короткая дополнительная строка (до 100 символов):
  второе пожелание, короткая строчка четверостишия или тёплая фраза-
  продолжение. НЕ повторяй teaser. Без подзаголовков <b>, без списка
  источников, без "Крючок"/"Вывод"/"Лид" — просто одна живая строка.
- title — короткое название повода (для внутреннего дедупа тем, не
  показывается в посте отдельным заголовком).
- image_prompt — только английский, 1-2 предложения: тёплая, уютная,
  жизненная сцена под повод (никаких надписей и цифр на картинке).

Общий объём teaser+body_html — не больше {teaser_max_length} символов.
ЗАПРЕЩЕНО: длинные абзацы, канцелярские клише («поздравляем вас с этим
замечательным праздником»), рифмы уровня открыток из 90-х."""
